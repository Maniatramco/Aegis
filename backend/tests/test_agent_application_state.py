@pytest.mark.parametrize('selected',[True,False])
def test_prompt_status_distinguishes_saved_from_selected_without_model_guessing(system,monkeypatch,selected):
    s=system;d=dataset(s);t=template(s)
    monkeypatch.setattr(providers,'plan',lambda *args:pytest.fail('Prompt status must come from verified records.'))
    monkeypatch.setattr(providers,'general_answer',lambda *args:pytest.fail('Prompt status must not be invented.'))
    p=plan(s,d,text='Is my prompt saved?',template_id=t['id'] if selected else '')
    result=events(reply(s,p))[-1]['message']['text']
    if selected:assert t['name'] in result and 'saved and selected' in result
    else:assert 'No prompt template is currently selected' in result and '1 saved prompt template is available' in result
    assert 'selected_prompt' not in result and 'null' not in result and 'no saved prompts' not in result

