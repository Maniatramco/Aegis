def test_followup_general_answers_receive_owned_dataset_prompt_and_attachment_state(system,monkeypatch):
    s=system;d=dataset(s,'Current dataset');upload(s,d);t=template(s)
    other=dataset(s,'Other dataset');upload(s,other)
    planner(monkeypatch,proposal((),answer_mode='general'));seen=[]
    async def answer(question,sources,history):
        context=providers.settings()['agent_context'];seen.append(context)
        assert context['selected_dataset']=='Current dataset'
        assert context['selected_prompt']=={'name':t['name'],'saved':True}
        assert context['ready_document_count']==1 and context['attached_documents']==['draft.pdf']
        yield 'Your selected prompt is saved; draft.pdf is attached, awaiting an upload workflow.'
    monkeypatch.setattr(providers,'answer_stream_async',answer)
    p=plan(s,d,text='What should I do next?',template_id=t['id'],attached_filenames=['draft.pdf'])
    assert events(reply(s,p))[-1]['message']['status']=='completed'
    assert len(seen)==1

