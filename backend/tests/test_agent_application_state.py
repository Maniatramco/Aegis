@pytest.mark.parametrize('text',['upload it','Upload this!','please upload the prompt template','can you upload it'])
def test_saved_prompt_upload_request_acknowledges_real_state_without_model_or_jobs(system,monkeypatch,text):
    s=system;d=dataset(s,'Selected dataset')
    t=post(s,'/api/templates',{'name':'Saved JSON prompt','dataset_id':d['id'],'schema':{'type':'object','properties':{},'required':[],'additionalProperties':False}})
    monkeypatch.setattr(providers,'plan',lambda *args:pytest.fail('Saved prompt state must not be guessed by a planner.'))
    monkeypatch.setattr(providers,'general_answer',lambda *args:pytest.fail('Verified upload status must not be generated by a model.'))
    p=plan(s,d,text=text,template_id=t['id'],answer_scope='documents')
    assert p['calls']==[] and p['answer_mode']=='general'
    result=events(reply(s,p))[-1]['message']
    assert result['status']=='completed' and result['citations']==[]
    assert 'Saved JSON prompt' in result['text'] and 'already saved and selected' in result['text'] and 'Selected dataset' in result['text']
    assert "don't upload" not in result['text'] and 'classification' not in result['text']
    assert s.api.get('/api/documents').json()==[] and s.api.get('/api/jobs').json()==[]
    assert len(s.api.get('/api/templates').json())==1
    assert s.api.get('/api/agent-v2/plans/'+p['id']).json()['chat']['id']==result['id']

