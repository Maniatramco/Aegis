-- Only the dedicated local Free database is supported by this launcher.
-- Rows are private to each connection and disappear when that connection closes.
CREATE GLOBAL TEMPORARY TABLE AEGIS_LOCAL_AI.LOCAL_DATASETS (
 DATASET_ID VARCHAR2(64) PRIMARY KEY,
 DATASET_NAME VARCHAR2(1000),
 CLASSIFICATION VARCHAR2(40),
 ACCOUNTABLE_OWNER VARCHAR2(200),
 STEWARD VARCHAR2(200),
 STATUS VARCHAR2(40)
) ON COMMIT PRESERVE ROWS;
CREATE GLOBAL TEMPORARY TABLE AEGIS_LOCAL_AI.LOCAL_DOCUMENTS (
 DOCUMENT_ID VARCHAR2(64) PRIMARY KEY,
 DATASET_ID VARCHAR2(64),
 DOCUMENT_NAME VARCHAR2(1000),
 STATUS VARCHAR2(40),
 SIZE_BYTES NUMBER
) ON COMMIT PRESERVE ROWS;
CREATE GLOBAL TEMPORARY TABLE AEGIS_LOCAL_AI.LOCAL_EXTRACTIONS (
 EXTRACTION_ID VARCHAR2(64) PRIMARY KEY,
 DATASET_ID VARCHAR2(64),
 EXTRACTION_NAME VARCHAR2(1000),
 STATUS VARCHAR2(40),
 REVIEW_STATUS VARCHAR2(100)
) ON COMMIT PRESERVE ROWS;
COMMENT ON TABLE AEGIS_LOCAL_AI.LOCAL_DATASETS IS 'Complete authorized dataset metadata in this connection only. No document contents or extracted values.';
COMMENT ON TABLE AEGIS_LOCAL_AI.LOCAL_DOCUMENTS IS 'Authorized document metadata. Join DATASET_ID to LOCAL_DATASETS.DATASET_ID.';
COMMENT ON TABLE AEGIS_LOCAL_AI.LOCAL_EXTRACTIONS IS 'Authorized extraction run metadata. Join DATASET_ID to LOCAL_DATASETS.DATASET_ID. No extracted values.';
